import json
from pathlib import Path

from django.contrib.auth.models import Permission
from django.contrib.contenttypes.models import ContentType
from django.core.management import call_command
from django.core.management.base import BaseCommand, CommandError
from django.db import connection, transaction

from apps.core.database_snapshot import managed_models, verify_database


class Command(BaseCommand):
    help = "Import an audited SQLite fixture into an EMPTY PostgreSQL database, preserving IDs."

    def add_arguments(self, parser):
        parser.add_argument("--fixture", type=Path, required=True)
        parser.add_argument("--manifest", type=Path, required=True)

    @transaction.atomic
    def handle(self, *args, **options):
        if connection.vendor != "postgresql":
            raise CommandError("This command only imports into an empty PostgreSQL database")
        if not options["fixture"].is_file() or not options["manifest"].is_file():
            raise CommandError("Existing fixture and manifest files are required")
        autogenerated = {"contenttypes.contenttype", "auth.permission"}
        populated = [
            model._meta.label_lower
            for model in managed_models()
            if model._meta.label_lower not in autogenerated and model._base_manager.exists()
        ]
        if populated:
            raise CommandError("Refusing to overwrite non-empty database: " + ", ".join(populated))
        manifest = json.loads(options["manifest"].read_text(encoding="utf-8"))
        # Only migration-generated defaults in an otherwise empty target are replaced.
        # The surrounding transaction restores them if loading or verification fails.
        Permission.objects.all().delete()
        ContentType.objects.all().delete()
        call_command("loaddata", str(options["fixture"]), verbosity=0)
        connection.check_constraints()
        verify_database(manifest)
        self.stdout.write("PostgreSQL import verified: all records and primary keys preserved")

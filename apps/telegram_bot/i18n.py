def t(language, key, **kwargs):
    language = language if language in TEXTS else "ru"
    if key in TEMPLATE_MESSAGE_KEYS:
        return render_message_template(language, key, kwargs)
    template = TEXTS[language].get(key) or TEXTS["ru"][key]
    return template.format(**kwargs)


def render_weekly_report(language, start, end, data):
    return t(
        language,
        "weekly_report",
        start=start.strftime("%d.%m"),
        end=end.strftime("%d.%m.%Y"),
        **data,
    )
